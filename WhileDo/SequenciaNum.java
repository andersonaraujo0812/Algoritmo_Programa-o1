/*
Escreva um algoritmo que imprima a sequência do número 100 ao 200.

*/

package WhileDo;


public class SequenciaNum {
    public static void main(String[] args) {

        int a = 100;
        


        while (a<=200) {
            System.out.println(a);
            a++;            
        }

    }
    
}
