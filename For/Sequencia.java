/*
Faça um programa que imprima a seguinte sequência:
– 100, 99, 98, . . . 1.

*/

package For;

public class Sequencia {
    public static void main(String[] args) {
        System.out.println("Algoritmo para imprimir a sequencia de 100 até 1\n");
        for(int i = 100;i>=1;i--){
        System.out.println(i);
        }
    }
}
